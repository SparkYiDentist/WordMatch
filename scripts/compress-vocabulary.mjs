import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const projectRoot = process.cwd()
const sourcePath = path.join(projectRoot, 'miniprogram', 'data', 'vocabulary', 'generated-data.ts')
const outputPath = path.join(projectRoot, 'miniprogram', 'data', 'vocabulary', 'generated-compressed-data.ts')

const source = await readFile(sourcePath, 'utf8')
const assignmentStart = source.indexOf('=[', source.indexOf('export const VOCABULARY_DATA'))
if (assignmentStart < 0) throw new Error('VOCABULARY_DATA assignment not found')
const rows = JSON.parse(source.slice(assignmentStart + 1).trim())
const input = new TextEncoder().encode(JSON.stringify(rows))

const keyAt = index => (
  index + 2 < input.length
    ? (input[index] << 16) | (input[index + 1] << 8) | input[index + 2]
    : -1
)

const chains = new Map()
const output = [
  input.length & 255,
  (input.length >>> 8) & 255,
  (input.length >>> 16) & 255,
  (input.length >>> 24) & 255,
]

const remember = index => {
  const key = keyAt(index)
  if (key < 0) return
  const positions = chains.get(key)
  if (positions) positions.push(index)
  else chains.set(key, [index])
}

let cursor = 0
while (cursor < input.length) {
  const flagsIndex = output.length
  output.push(0)
  let flags = 0

  for (let bit = 0; bit < 8 && cursor < input.length; bit += 1) {
    const positions = chains.get(keyAt(cursor)) || []
    let bestLength = 0
    let bestOffset = 0
    let inspected = 0

    for (let index = positions.length - 1; index >= 0 && inspected < 96; index -= 1, inspected += 1) {
      const candidate = positions[index]
      const offset = cursor - candidate
      if (offset > 65535) break
      let length = 0
      const limit = Math.min(258, input.length - cursor)
      while (length < limit && input[candidate + length] === input[cursor + length]) length += 1
      if (length > bestLength) {
        bestLength = length
        bestOffset = offset
        if (length === limit) break
      }
    }

    const advance = bestLength >= 4 ? bestLength : 1
    if (bestLength >= 4) {
      flags |= 1 << bit
      output.push(bestOffset & 255, (bestOffset >>> 8) & 255, bestLength - 3)
    } else {
      output.push(input[cursor])
    }
    for (let index = 0; index < advance; index += 1) remember(cursor + index)
    cursor += advance
  }
  output[flagsIndex] = flags
}

const packed = Uint8Array.from(output)
const Z85_ALPHABET = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ.-:+=^!/*?&<>()[]{}@%$#'
let z85 = ''
for (let index = 0; index < packed.length; index += 4) {
  let value = (
    ((packed[index] || 0) * 0x1000000)
    + ((packed[index + 1] || 0) << 16)
    + ((packed[index + 2] || 0) << 8)
    + (packed[index + 3] || 0)
  )
  const encoded = new Array(5)
  for (let digit = 4; digit >= 0; digit -= 1) {
    encoded[digit] = Z85_ALPHABET[value % 85]
    value = Math.floor(value / 85)
  }
  z85 += encoded.join('')
}
const chunks = z85.match(/.{1,8192}/g) || []
const generated = `// Generated by scripts/compress-vocabulary.mjs; do not edit manually.\n`
  + `export const VOCABULARY_PACKED_BYTES=${packed.length}\n`
  + `export const VOCABULARY_DATA_Z85=[\n${chunks.map(chunk => JSON.stringify(chunk)).join(',\n')}\n].join('')\n`

await writeFile(outputPath, generated, 'utf8')
console.log(JSON.stringify({
  entries: rows.length,
  sourceBytes: input.length,
  packedBytes: packed.length,
  encodedBytes: Buffer.byteLength(z85),
  generatedBytes: Buffer.byteLength(generated),
  ratio: Number((packed.length / input.length).toFixed(3)),
}, null, 2))
